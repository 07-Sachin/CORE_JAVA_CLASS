class Bitwise_operator{
  public static void main(String[]args){
   int a= 10;
   int b=5;
   int c= a&b;
   System.out.println("AND : "+c);
   int d= a|b;
   System.out.println("OR : "+d);
   int e =a^b;
   System.out.println("XOR : "+e);
   int f = a<<b;
   System.out.println("LEFTSHIFT : "+f);
   int g = a>>b;
   System.out.println("RIGHTSHIFT : "+g);
  }
}
